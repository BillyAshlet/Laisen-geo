"""Pack Rin's 200 m handoff (Changchun, 4th ring) into app/data/changchun.js.

Usage: python3 -I scripts/build_changchun_grid.py <handoff_dir> <out_js>

Reads the three GeoTIFFs (same EPSG:32651 grid, 103 x 99) and rasterises the
expressway / arterial GeoJSON (WGS84) onto that grid. No pyproj here, so the
WGS84 -> UTM 51N projection is done with the standard transverse Mercator series.
"""
import json, math, sys
import numpy as np
import tifffile

src, out = sys.argv[1], sys.argv[2]
dem = tifffile.imread(f"{src}/rasters/DEM_Copernicus_DSM_200m.tif").astype(float)
lst = tifffile.imread(f"{src}/rasters/LST_2023_200m.tif").astype(float)
wc = tifffile.imread(f"{src}/rasters/WorldCover_2021_200m.tif").astype(int)
H, W = wc.shape
X0, Y0, CELL = 674600.0, 4872000.0, 200.0          # top-left corner, from verification.json


def utm51(lon, lat):
    a, f, k0 = 6378137.0, 1 / 298.257223563, 0.9996
    e2 = f * (2 - f); ep2 = e2 / (1 - e2)
    phi, lam = math.radians(lat), math.radians(lon - 123.0)   # zone 51 central meridian
    n = a / math.sqrt(1 - e2 * math.sin(phi) ** 2)
    t, c = math.tan(phi) ** 2, ep2 * math.cos(phi) ** 2
    A = math.cos(phi) * lam
    m = a * ((1 - e2 / 4 - 3 * e2**2 / 64 - 5 * e2**3 / 256) * phi
             - (3 * e2 / 8 + 3 * e2**2 / 32 + 45 * e2**3 / 1024) * math.sin(2 * phi)
             + (15 * e2**2 / 256 + 45 * e2**3 / 1024) * math.sin(4 * phi)
             - (35 * e2**3 / 3072) * math.sin(6 * phi))
    x = k0 * n * (A + (1 - t + c) * A**3 / 6 + (5 - 18 * t + t * t + 72 * c - 58 * ep2) * A**5 / 120) + 500000
    y = k0 * (m + n * math.tan(phi) * (A**2 / 2 + (5 - t + 9 * c + 4 * c * c) * A**4 / 24
                                       + (61 - 58 * t + t * t + 600 * c - 330 * ep2) * A**6 / 720))
    return x, y


def burn(path, level, grid):
    for feat in json.load(open(path))["features"]:
        if feat["properties"].get("is_link") in (True, "true"):
            continue
        g = feat["geometry"]
        lines = g["coordinates"] if g["type"] == "MultiLineString" else [g["coordinates"]]
        for line in lines:
            pts = [utm51(lon, lat) for lon, lat in line]
            for (xa, ya), (xb, yb) in zip(pts, pts[1:]):
                steps = max(1, int(math.hypot(xb - xa, yb - ya) / 50))   # sample every ~50 m
                for k in range(steps + 1):
                    x, y = xa + (xb - xa) * k / steps, ya + (yb - ya) * k / steps
                    c, r = int((x - X0) // CELL), int((Y0 - y) // CELL)
                    if 0 <= r < H and 0 <= c < W:
                        grid[r, c] = max(grid[r, c], level)


road = np.zeros((H, W), dtype=int)
burn(f"{src}/vectors/arterials.geojson", 1, road)
burn(f"{src}/vectors/expressways.geojson", 2, road)

def simplify(pts, tol):
    """Douglas–Peucker, for drawing roads as clean vector lines."""
    if len(pts) < 3:
        return pts
    (xa, ya), (xb, yb) = pts[0], pts[-1]
    L = math.hypot(xb - xa, yb - ya) or 1e-9
    d = [abs((xb - xa) * (ya - y) - (xa - x) * (yb - ya)) / L for x, y in pts[1:-1]]
    k = max(range(len(d)), key=d.__getitem__)
    if d[k] <= tol:
        return [pts[0], pts[-1]]
    return simplify(pts[:k + 2], tol)[:-1] + simplify(pts[k + 1:], tol)


def lines(path, level):
    out = []
    for feat in json.load(open(path))["features"]:
        if feat["properties"].get("is_link") in (True, "true"):
            continue
        g = feat["geometry"]
        for line in (g["coordinates"] if g["type"] == "MultiLineString" else [g["coordinates"]]):
            pts = [((x - X0) / CELL, (Y0 - y) / CELL) for x, y in (utm51(lon, lat) for lon, lat in line)]
            pts = simplify(pts, 0.3)                       # 0.3 cell = 60 m
            out.append([level, [round(v, 2) for p in pts for v in p]])
    return out


inside = wc > 0
clean = lambda a, d: [None if not ok else round(float(v), d) for v, ok in zip(a.ravel(), inside.ravel())]
data = {
    "w": W, "h": H, "cell": CELL, "origin": [X0, Y0], "crs": "EPSG:32651",
    "worldcover": wc.ravel().tolist(),           # ESA WorldCover classes; 0 = outside the 4th ring
    "dem": clean(dem, 1), "lst": clean(lst, 2),
    "road": (road * inside).ravel().tolist(),    # 0 none, 1 arterial, 2 expressway
    # Vector roads for drawing, in grid cell units (col, row): [level, [c0, r0, c1, r1, ...]]
    "roadLines": lines(f"{src}/vectors/arterials.geojson", 1) + lines(f"{src}/vectors/expressways.geojson", 2),
    "source": "Rin, four_ring_200m_handoff (2026-10-17): ESA WorldCover 2021, Copernicus GLO-30 DSM, LST 2023, OSM",
}
with open(out, "w") as fh:
    fh.write("// Generated by scripts/build_changchun_grid.py — do not edit by hand.\n")
    fh.write("const CHANGCHUN = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"{W}x{H}, inside {int(inside.sum())} cells, road cells {int((road * inside > 0).sum())}")
